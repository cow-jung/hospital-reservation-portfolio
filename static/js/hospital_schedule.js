// =====================================================================
// YYYY-MM-DD 생성
// =====================================================================

window.formatHospitalDate =
function (
    year,
    month,
    day
) {

    const monthText =
        String(month + 1)
            .padStart(2, "0");


    const dayText =
        String(day)
            .padStart(2, "0");


    return (
        year
        + "-"
        + monthText
        + "-"
        + dayText
    );
};



// =====================================================================
// 공휴일 확인
// =====================================================================

window.isHospitalHoliday =
function (
    year,
    month,
    day
) {

    const dateString =
        window.formatHospitalDate(
            year,
            month,
            day
        );


    return window.HOSPITAL_HOLIDAYS.includes(
        dateString
    );
};



// =====================================================================
// 해당 날짜가 휴진일인지 확인
//
// 일요일 또는 공휴일이면 true
// =====================================================================

window.isHospitalClosed =
function (
    year,
    month,
    day
) {

    const date =
        new Date(
            year,
            month,
            day
        );


    // 일요일
    if (date.getDay() === 0) {

        return true;
    }


    // 공휴일
    if (
        window.isHospitalHoliday(
            year,
            month,
            day
        )
    ) {

        return true;
    }


    return false;
};



// =====================================================================
// 해당 날짜 예약시간 반환
// =====================================================================

window.getHospitalTimes =
function (dateString) {

    const date =
        new Date(
            dateString + "T00:00:00"
        );


    // 일요일
    if (date.getDay() === 0) {

        return [];
    }


    // 공휴일
    if (
        window.HOSPITAL_HOLIDAYS.includes(
            dateString
        )
    ) {

        return [];
    }


    // 토요일
    if (date.getDay() === 6) {

        return window.SATURDAY_TIMES;
    }


    // 평일
    return window.WEEKDAY_TIMES;
};